import { createIssueUrl, inferTitle, rankRepositories } from "./router.js";

export async function initProposalRouter(env = globalThis) {
  const doc = env.document;
  const fetchImpl = env.fetch ?? globalThis.fetch;
  const nav = env.navigator ?? globalThis.navigator;

  const proposalInput = doc.querySelector("#proposal");
  const titleInput = doc.querySelector("#title");
  const repositorySelect = doc.querySelector("#repository");
  const suggestionsList = doc.querySelector("#suggestions");
  const issueLink = doc.querySelector("#issue-link");
  const copyButton = doc.querySelector("#copy-link");

  let repositories = [];
  let currentSuggestions = [];
  let catalogLoaded = false;
  let explicitSelectionKey = null;
  let lastAutoGeneratedTitle = "";
  let titleWasAutoGenerated = titleInput.value.trim() === "";

  function repositoryKey(repository) {
    return `${repository.owner}/${repository.name}`;
  }

  function selectedRepository() {
    if (explicitSelectionKey) {
      const explicitMatch = repositories.find((repository) => repositoryKey(repository) === explicitSelectionKey);
      if (explicitMatch) return explicitMatch;
    }
    return repositories.find((repository) => repositoryKey(repository) === repositorySelect.value) ?? repositories[0];
  }

  function updateIssueLink() {
    const repo = selectedRepository();
    const title = titleInput.value.trim();
    const body = proposalInput.value.trim();
    const enabled = Boolean(catalogLoaded && repo && title && body);

    issueLink.href = enabled ? createIssueUrl(repo, title, body) : "#";
    issueLink.setAttribute("aria-disabled", String(!enabled));
  }

  function recordExplicitRepositorySelection() {
    if (!catalogLoaded || !repositorySelect.value) return;
    explicitSelectionKey = repositorySelect.value;
    updateIssueLink();
  }

  function renderCatalogFailureNotice() {
    repositorySelect.replaceChildren();
    repositorySelect.disabled = true;
    const notice = doc.createElement("li");
    notice.className = "catalog-failure-notice";
    notice.textContent = "Unable to load repository catalog. Reload the page to retry.";
    suggestionsList.replaceChildren(notice);
    updateIssueLink();
  }

  function renderRepositoryOptions() {
    const orderedRepositories = [...currentSuggestions.map(({ repository }) => repository)];
    if (explicitSelectionKey && !orderedRepositories.some((repo) => repositoryKey(repo) === explicitSelectionKey)) {
      const explicitRepo = repositories.find((repo) => repositoryKey(repo) === explicitSelectionKey);
      if (explicitRepo) orderedRepositories.unshift(explicitRepo);
    }

    repositorySelect.disabled = orderedRepositories.length === 0;
    repositorySelect.replaceChildren(
      ...orderedRepositories.map((repository) => {
        const option = doc.createElement("option");
        const key = repositoryKey(repository);
        option.value = key;
        option.textContent = key;
        return option;
      })
    );

    const targetValue = explicitSelectionKey ?? (orderedRepositories[0] ? repositoryKey(orderedRepositories[0]) : "");
    if (targetValue) {
      repositorySelect.value = targetValue;
    }
  }

  function renderSuggestions() {
    suggestionsList.replaceChildren(
      ...currentSuggestions.map(({ repository, confidence, matched }) => {
        const item = doc.createElement("li");
        const header = doc.createElement("div");
        const title = doc.createElement("strong");
        const score = doc.createElement("span");
        const description = doc.createElement("p");
        const matches = doc.createElement("small");
        const key = repositoryKey(repository);

        header.className = "suggestion-header";
        title.textContent = key;
        score.textContent = `${confidence}%`;
        description.textContent = repository.description;
        matches.textContent = matched.length ? `Matched: ${matched.join(", ")}` : "Waiting for proposal detail";

        header.append(title, score);
        item.append(header, description, matches);
        item.addEventListener("click", () => {
          explicitSelectionKey = key;
          renderRepositoryOptions();
          updateIssueLink();
        });
        return item;
      })
    );
  }

  function updateSuggestions() {
    const proposal = proposalInput.value;
    if (titleInput.value.trim() !== "" && titleInput.value !== lastAutoGeneratedTitle) {
      titleWasAutoGenerated = false;
    }
    if (titleWasAutoGenerated) {
      lastAutoGeneratedTitle = inferTitle(proposal);
      titleInput.value = lastAutoGeneratedTitle;
    }

    if (!catalogLoaded) {
      updateIssueLink();
      return;
    }

    currentSuggestions = rankRepositories(repositories, proposal, 5);
    renderRepositoryOptions();
    renderSuggestions();
    updateIssueLink();
  }

  // Register listeners BEFORE awaiting catalog load so early user edits are never dropped.
  titleInput.addEventListener("input", () => {
    titleWasAutoGenerated = false;
    updateIssueLink();
  });
  proposalInput.addEventListener("input", updateSuggestions);
  repositorySelect.addEventListener("change", recordExplicitRepositorySelection);
  repositorySelect.addEventListener("input", recordExplicitRepositorySelection);
  repositorySelect.addEventListener("click", recordExplicitRepositorySelection);

  copyButton.addEventListener("click", async () => {
    if (issueLink.getAttribute("aria-disabled") === "true") {
      return;
    }
    await nav.clipboard.writeText(issueLink.href);
    copyButton.textContent = "Copied";
    setTimeout(() => {
      copyButton.textContent = "Copy Link";
    }, 1400);
  });

  async function loadRepositories() {
    try {
      const response = await fetchImpl("./repositories.json");
      if (!response || !response.ok) {
        throw new Error(`Failed to fetch repositories: ${response?.status ?? "unknown"}`);
      }
      const data = await response.json();
      if (!Array.isArray(data) || data.length === 0) {
        throw new Error("Repository catalog is empty");
      }
      repositories = data;
      catalogLoaded = true;
      updateSuggestions();
      return repositories;
    } catch {
      catalogLoaded = false;
      repositories = [];
      renderCatalogFailureNotice();
      return [];
    }
  }

  await loadRepositories();
  return {
    loadRepositories,
    updateSuggestions,
    getExplicitSelectionKey: () => explicitSelectionKey,
  };
}

if (typeof globalThis.document !== "undefined" && globalThis.document.querySelector("#proposal")) {
  await initProposalRouter(globalThis);
}

